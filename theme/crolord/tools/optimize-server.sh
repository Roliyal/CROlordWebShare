#!/usr/bin/env bash
# Narrow static-asset caching/compression for an existing native Apache WordPress site.
set -Eeuo pipefail
umask 077
CROLORD_MODE="${1:---apply}"
CROLORD_ROOT="${CROLORD_WP_ROOT:-/var/www/html}"
case "$CROLORD_MODE" in --check|--apply) ;; *) echo '用法：bash optimize-server.sh [--check|--apply]'; exit 1;; esac
[[ "$CROLORD_ROOT" =~ ^/[a-zA-Z0-9_./-]+$ && -f "$CROLORD_ROOT/wp-load.php" ]] || { echo '未找到 WordPress 根目录，尚未修改配置。'; exit 1; }
CROLORD_ROOT=$(readlink -f "$CROLORD_ROOT")
CROLORD_CTL=''
for CROLORD_TOOL in apachectl apache2ctl; do
 if command -v "$CROLORD_TOOL" >/dev/null 2>&1; then CROLORD_CTL=$(command -v "$CROLORD_TOOL"); break; fi
done
[[ -n "$CROLORD_CTL" ]] || { echo '未识别原生 Apache 管理命令，尚未修改配置。'; exit 1; }
"$CROLORD_CTL" -t
CROLORD_MODULES=$("$CROLORD_CTL" -M 2>/dev/null)
[[ "$CROLORD_MODULES" == *headers_module* ]] || { echo 'Apache 未启用 mod_headers，尚未修改；请先启用该模块。'; exit 1; }
if [[ -d /etc/httpd/conf.d ]]; then CROLORD_TARGET=/etc/httpd/conf.d/crolord-static-performance.conf
elif [[ -d /etc/apache2/conf-enabled ]]; then CROLORD_TARGET=/etc/apache2/conf-enabled/crolord-static-performance.conf
else echo 'Apache 配置目录未识别，尚未修改。'; exit 1; fi
[[ ! -L "$CROLORD_TARGET" ]] || { echo '目标配置为符号链接，尚未修改。'; exit 1; }
CROLORD_TEMP=$(mktemp -d)
trap 'rm -rf -- "$CROLORD_TEMP"' EXIT
: > "$CROLORD_TEMP/config"
CROLORD_COUNT=0
for CROLORD_ASSETS in "$CROLORD_ROOT/wp-content/themes/crolord/assets" "$CROLORD_ROOT/wp-content/plugins/crolord-chatgpt/assets" "$CROLORD_ROOT/wp-content/plugins/crolord-map/assets" "$CROLORD_ROOT/wp-content/plugins/crolord-comment-tools/assets"; do
 [[ -d "$CROLORD_ASSETS" ]] || continue
 CROLORD_COUNT=$((CROLORD_COUNT+1))
 cat >> "$CROLORD_TEMP/config" <<CONF
# Generated by crolord; public static assets only.
<Directory "$CROLORD_ASSETS">
    <FilesMatch "\\.(?:css|js|svg|json|geojson|woff2?|png|jpe?g|webp|gif|avif)$">
        Header set Cache-Control "public, max-age=604800"
    </FilesMatch>
    <IfModule deflate_module>
        <IfModule filter_module>
            AddOutputFilterByType DEFLATE text/css text/javascript application/javascript application/json application/geo+json image/svg+xml
        </IfModule>
    </IfModule>
</Directory>
CONF
done
[[ "$CROLORD_COUNT" -gt 0 ]] || { echo '未发现 crolord 静态资源目录，尚未修改。'; exit 1; }
echo "目标：$CROLORD_TARGET"
if [[ "$CROLORD_MODULES" != *deflate_module* || "$CROLORD_MODULES" != *filter_module* ]]; then
 echo '当前压缩模块不完整；本次可启用静态缓存，压缩需服务器启用 mod_deflate 与 mod_filter。'
fi
if [[ "$CROLORD_MODE" == --check ]]; then cat "$CROLORD_TEMP/config"; echo '检查完成，未写入或重载。'; exit 0; fi
[[ $EUID -eq 0 ]] || { echo '请用 sudo bash 运行以写入 Apache 配置。'; exit 1; }
CROLORD_BACKUP=''
if [[ -e "$CROLORD_TARGET" ]]; then CROLORD_BACKUP="${CROLORD_TARGET}.bak.$(date +%Y%m%d-%H%M%S)-$$"; cp -p -- "$CROLORD_TARGET" "$CROLORD_BACKUP"; fi
CROLORD_INSTALLED=0
crolord_restore() {
 if [[ -n "$CROLORD_BACKUP" ]]; then cp -p -- "$CROLORD_BACKUP" "$CROLORD_TARGET"; else rm -f -- "$CROLORD_TARGET"; fi
 CROLORD_INSTALLED=0
}
trap 'CROLORD_STATUS=$?; if [[ "$CROLORD_INSTALLED" == 1 ]]; then crolord_restore; echo "执行异常，已恢复此前配置。"; fi; rm -rf -- "$CROLORD_TEMP"; exit "$CROLORD_STATUS"' EXIT
cp -- "$CROLORD_TEMP/config" "$CROLORD_TARGET"; chmod 644 "$CROLORD_TARGET"; CROLORD_INSTALLED=1
if ! "$CROLORD_CTL" -t; then crolord_restore; echo '配置检查失败，已恢复；未重载。'; exit 1; fi
CROLORD_INCLUDES=$("$CROLORD_CTL" -t -D DUMP_INCLUDES 2>&1)
if [[ "$CROLORD_INCLUDES" != *"$CROLORD_TARGET"* ]]; then crolord_restore; echo '新文件未被当前 Apache 配置包含，已恢复；未重载。'; exit 1; fi
if ! "$CROLORD_CTL" graceful; then
 crolord_restore
 "$CROLORD_CTL" -t && "$CROLORD_CTL" graceful || true
 echo '重载未确认成功，已恢复此前配置；请检查 Apache 日志。'; exit 1
fi
CROLORD_INSTALLED=0
echo 'Apache 校验通过，已平滑重载。静态资源缓存 7 天；请求仍按版本 URL 更新。'
[[ -z "$CROLORD_BACKUP" ]] || echo "配置备份：$CROLORD_BACKUP"
echo "回退：恢复该备份；首次应用则删除 $CROLORD_TARGET，再执行 $CROLORD_CTL -t 与 $CROLORD_CTL graceful。"
if command -v curl >/dev/null 2>&1; then
 if curl --silent --show-error --compressed --connect-timeout 5 --max-time 20 -D "$CROLORD_TEMP/headers" -o /dev/null 'https://roliyal.com/wp-content/themes/crolord/assets/css/home.min.css?ver=2.4.5'; then
  awk 'tolower($0) ~ /^(http\/|content-encoding:|cache-control:|vary:)/ {gsub(/\r/,"");print}' "$CROLORD_TEMP/headers"
  echo '以上为公网资源响应，请确认 HTTP 200、Cache-Control 与压缩标头；前置网关也可能改写响应。'
 else echo 'Apache 已完成校验与重载；本机未能验证公网响应，请在浏览器检查缓存与压缩。'; fi
fi
