<?php
if (!defined('ABSPATH')) { exit; }

/** Read-only compatibility for records created by retired WeChat transports. */
final class Crolord_Publisher_Wechat_History {
    public static function unavailable() {
        return new WP_Error('wechat_unavailable', '微信旧通道已移除，不再创建或执行任务；历史记录与发布 ID 保留。');
    }
    public static function boot() {
        // Only the cleanup callback survives. No login, REST device or SDK hooks.
        add_action('crolord_publisher_cloud_cleanup', array(__CLASS__, 'cleanup'));
    }
    public static function upgrade() {
        global $wpdb;
        $device=get_option('crolord_publisher_local_device',null);
        if(is_array($device)){$device['enabled']=false;$device['token_hash']='';$device['pair_hash']='';$device['pair_expires']=0;update_option('crolord_publisher_local_device',$device,false);}
        $last = 0;
        do {
            $ids = $wpdb->get_col($wpdb->prepare('SELECT id FROM ' . Crolord_Publisher_Store::table() . " WHERE platform='wechat' AND id>%d ORDER BY id LIMIT 100", $last));
            foreach ($ids as $id) {
                $last = (int) $id;
                wp_clear_scheduled_hook('crolord_publisher_due', array($last));
                // Remove only public copies generated by the old cloud exporter.
                self::cleanup($last);
            }
        } while (count($ids) === 100);
        wp_unschedule_hook('crolord_publisher_cloud_cleanup');
    }
    public static function cleanup($id) {
        if (!is_scalar($id) || !preg_match('/^[1-9][0-9]*$/D', (string) $id)) { return; }
        $uploads = realpath(wp_get_upload_dir()['basedir']);
        if (!$uploads) { return; }
        $root = $uploads . DIRECTORY_SEPARATOR . 'crolord-publisher-cloud';
        $dir = $root . DIRECTORY_SEPARATOR . (string) $id;
        if (is_link($root) || is_link($dir) || !is_dir($dir) || realpath($dir) !== $dir) { return; }
        foreach (scandir($dir) as $name) {
            if ($name !== 'index.html' && !preg_match('/^[a-f0-9]{64}\.(?:jpg|png|mp4)$/D', $name)) { continue; }
            $path = $dir . DIRECTORY_SEPARATOR . $name;
            if (!is_link($path) && is_file($path) && realpath($path) === $path) { wp_delete_file($path); }
        }
        // An unknown file or directory is left alone.
        $left = array_diff(scandir($dir), array('.', '..'));
        if (!$left) { rmdir($dir); }
    }
    public static function media_file($media) {
        $file = get_attached_file((int) ($media['id'] ?? 0));
        $base = realpath(wp_get_upload_dir()['basedir']);
        $real = $file ? realpath($file) : false;
        if (!$base || !$real || strpos($real, $base . DIRECTORY_SEPARATOR) !== 0 || !is_file($real) || !is_readable($real)
            || get_post_mime_type((int) $media['id']) !== 'video/mp4'
            || !hash_equals((string) ($media['sha256'] ?? ''), hash_file('sha256', $real))) {
            throw new RuntimeException('历史视频已改变或不可读取，无法导出。');
        }
        return $real;
    }
    public static function render() {
        echo '<section class="cp-wechat-status"><h2>微信朋友圈</h2><p>旧执行器与授权入口已移除。仅保留旧队列、记录和发布 ID，不会重新执行。</p><p class="description">历史任务与发布 ID 保留。旧任务仅供查看，不会恢复发表；不会把下载素材或接口接收误报成发布成功。</p></section>';
    }
}
